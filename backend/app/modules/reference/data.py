# Address lines; `{region}` is a state, province or prefecture.
ADDRESS_STYLES: dict[str, list[str]] = {
    "postal_city": ["{street}", "{postal_code} {city}"],
    "city_postal": ["{street}", "{city} {postal_code}"],
    "city_region_postal": ["{street}", "{city}, {region} {postal_code}"],
    "city_newline_postal": ["{street}", "{city}", "{postal_code}"],
    "postal_first": ["{postal_code}", "{region} {city}", "{street}"],
    "no_postal": ["{street}", "{city}"],
}


def F(day: str, name: str) -> dict[str, Any]:  # noqa: N802 - short rule constructors
    return {"name": name, "date": day}


def E(offset: int, name: str) -> dict[str, Any]:  # noqa: N802
    return {"name": name, "easter": offset}


def N(month: int, weekday: int, n: int, name: str) -> dict[str, Any]:  # noqa: N802
    return {"name": name, "nth": [month, weekday, n]}


def B(month: int, day: int, weekday: int, name: str) -> dict[str, Any]:  # noqa: N802
    return {"name": name, "before": [month, day, weekday]}


def A(month: int, day: int, weekday: int, name: str) -> dict[str, Any]:  # noqa: N802
    return {"name": name, "after": [month, day, weekday]}



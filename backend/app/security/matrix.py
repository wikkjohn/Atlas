"""The authorization matrix (Phase 86): what every API route requires, read from the code.

Each route under `/api/v1` is either public (signing in, before there is a session), open to
any signed-in user, or guarded by one permission through `Authorized(...)`. The matrix is
read from the routes' dependencies, so it is what the server enforces, not what a document
says. `tests/authorization_matrix.json` holds the reviewed copy: a change to any route's
requirement fails the test until the copy is regenerated (`python -m app.cli authz-matrix
--write`) and the difference reviewed. `docs/authorization-matrix.md` is generated from it.
"""

from collections.abc import Iterator
from typing import Any

from fastapi import FastAPI
from fastapi.dependencies.models import Dependant
from fastapi.routing import APIRoute

from app.core.permissions import ROLE_PERMISSIONS, SERVICE_ROLES, Permission, RoleCode
from app.modules.identity.dependencies import get_current_user

PUBLIC = "public"
SIGNED_IN = "signed_in"


def _calls(dependant: Dependant) -> Iterator[Any]:
    for sub in dependant.dependencies:
        yield sub.call
        yield from _calls(sub)


def requirement(route) -> str:
    """The permission a route requires, `signed_in`, or `public`."""
    permissions = {
        str(call.required_permission)
        for call in _calls(route.dependant)
        if getattr(call, "required_permission", None) is not None
    }
    if len(permissions) > 1:
        raise ValueError(f"{route.path} requires several permissions: {sorted(permissions)}")
    if permissions:
        return permissions.pop()
    if any(call is get_current_user for call in _calls(route.dependant)):
        return SIGNED_IN
    return PUBLIC


def _effective(app: FastAPI) -> Iterator[Any]:
    """Every route as served: plain routes, and those of included routers (FastAPI keeps
    those as included-router objects with their effective contexts)."""
    for route in app.routes:
        if isinstance(route, APIRoute):
            yield route
        elif hasattr(route, "effective_route_contexts"):
            yield from route.effective_route_contexts()


def routes(app: FastAPI) -> dict[str, str]:
    """`METHOD /path` → requirement, for every route under /api/v1."""
    matrix: dict[str, str] = {}
    for route in _effective(app):
        if route.path.startswith("/api/v1"):
            for method in sorted(set(route.methods) - {"HEAD", "OPTIONS"}):
                matrix[f"{method} {route.path}"] = requirement(route)
    return dict(sorted(matrix.items(), key=lambda kv: (kv[0].split(" ", 1)[1], kv[0])))


def roles_holding(permission: str) -> list[str]:
    people = [r for r in RoleCode if r not in SERVICE_ROLES]
    if permission in (PUBLIC, SIGNED_IN):
        return [r.value for r in people]
    return [r.value for r in people if Permission(permission) in ROLE_PERMISSIONS[r]]


def markdown(matrix: dict[str, str]) -> str:
    """The generated reference: each route, its requirement and the roles that may call it."""
    people = [r for r in RoleCode if r not in SERVICE_ROLES]
    abbreviations = {
        "platform_administrator": "ADM", "global_executive": "GEX", "regional_executive": "REX",
        "department_manager": "MGR", "banking_employee": "EMP", "compliance_officer": "CMP",
        "ai_researcher": "AIR", "auditor": "AUD",
    }  # fmt: skip
    header = (
        "| Method | Path | Requires | "
        + " | ".join(abbreviations.get(r.value, r.value) for r in people)
        + " |"
    )
    lines = [
        "# Authorization matrix",
        "",
        "Generated by `python -m app.cli authz-matrix --write` from the routes' own "
        "dependencies (Phase 86); do not edit by hand. ✓ marks the roles that may call a "
        "route. Scopes, four-eyes rules and other business rules then apply on top.",
        "",
        "Roles: " + ", ".join(f"{abbreviations.get(r.value, r.value)} = {r.value}" for r in people),
        "",
        f"{len(matrix)} routes: "
        f"{sum(1 for v in matrix.values() if v == PUBLIC)} public, "
        f"{sum(1 for v in matrix.values() if v == SIGNED_IN)} for any signed-in user, "
        f"{sum(1 for v in matrix.values() if v not in (PUBLIC, SIGNED_IN))} behind a permission.",
        "",
        header,
        "| --- | --- | --- | " + " | ".join("---" for _ in people) + " |",
    ]
    for key, need in matrix.items():
        method, path = key.split(" ", 1)
        allowed = set(roles_holding(need))
        cells = " | ".join("✓" if r.value in allowed else "" for r in people)
        shown = f"`{need}`" if need not in (PUBLIC, SIGNED_IN) else need.replace("_", " ")
        lines.append(f"| {method} | `{path}` | {shown} | {cells} |")
    return "\n".join(lines) + "\n"

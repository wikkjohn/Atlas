@dataclass(frozen=True)
class CountryData:
    code: str
    alpha3: str
    name: str
    region: str
    currency: str
    timezone: str
    languages: tuple[str, ...]
    calling_code: str
    regulator: tuple[str, str]  # (name, abbreviation) of the banking supervisor
    postal: tuple[str, ...]  # postal-code masks; empty: no postal codes in use
    address: str  # a key of ADDRESS_STYLES
    holidays: tuple[dict[str, Any], ...]
    weekend: tuple[int, ...] = SAT_SUN
    national_id: tuple[str, str] | None = None  # (document name, number mask)
    passport: str = "A9999999"
    easter: str = "western"
    observance: str = "none"  # none, next_weekday, nearest_weekday, sunday_to_next
    notes: tuple[str, ...] = field(default=())


def _c(
    code: str,
    alpha3: str,
    name: str,
    region: str,
    currency: str,
    timezone: str,
    languages: list[str],
    calling_code: str,
    regulator: tuple[str, str],
    postal: list[str],
    address: str,
    holidays: list[dict[str, Any]],
    **extra: Any,
) -> CountryData:
    return CountryData(
        code, alpha3, name, region, currency, timezone, tuple(languages), calling_code,
        regulator, tuple(postal), address, tuple(holidays), **extra,
    )  # fmt: skip


